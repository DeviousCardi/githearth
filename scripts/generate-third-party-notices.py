#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_NOTICES from Cargo.lock.

Lists every third-party (non-workspace) crate that the release binaries
(`githearth-server`, which the container image ships, and `githearth-cli`)
link against, with the SPDX license expression each crate declares.

The list is resolved offline from Cargo.lock via `cargo metadata --locked
--offline`, so both regeneration and the stale check in scripts/ci.sh are
fast and need no network. Test-only (dev) dependencies are excluded: they are
never compiled into the release binary or the container image.

Usage:
  scripts/generate-third-party-notices.py           # rewrite THIRD_PARTY_NOTICES
  scripts/generate-third-party-notices.py --check   # exit non-zero if stale
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICES = ROOT / "THIRD_PARTY_NOTICES"

# The binaries that are released: the server (also shipped in the container
# image) and the `githearth` command-line interface.
BINARY_CRATES = {"githearth-server", "githearth-cli"}

# A crate whose manifest only declares `license-file` (no SPDX `license`
# field) cannot be resolved offline, so it would otherwise be written out as
# "Unspecified". Every such crate in the release build graph must be listed
# here with the SPDX expression its license file corresponds to; the generator
# and `--check` fail with a clear message instead of underreporting a license.
ALLOWLIST: dict[str, str] = {}

HEADER = """\
GitHearth third-party notices
=============================

The GitHearth server and command-line interface are distributed with the
third-party components listed below. Each component is available under its
own license, identified here by the SPDX expression that the component
declares. The full license text for a component is available from its source,
most often the crates.io entry recorded in Cargo.lock.

This file is generated by scripts/generate-third-party-notices.py from
Cargo.lock and lists every third-party crate in the build graph of the
release binaries (runtime and build dependencies; test-only dependencies are
excluded). Do not edit it by hand: regenerate it with
`scripts/generate-third-party-notices.py` after any dependency change.

"""


def load_metadata() -> dict:
    proc = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--offline"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        sys.exit(proc.returncode)
    return json.loads(proc.stdout)


class MissingLicenseError(Exception):
    """A third-party crate declares no SPDX license and is not allowlisted."""

    def __init__(self, name: str, version: str) -> None:
        super().__init__(
            f"{name} {version} declares no SPDX license expression "
            "(only `license-file`); add it to ALLOWLIST in "
            "scripts/generate-third-party-notices.py with its licence."
        )


def license_expression(package: dict) -> str:
    expression = package.get("license")
    if expression:
        return expression
    expression = ALLOWLIST.get(package["name"])
    if expression is None:
        raise MissingLicenseError(package["name"], package["version"])
    return expression


def third_party_dependencies(meta: dict) -> list[tuple[str, str, str]]:
    packages = {p["id"]: p for p in meta["packages"]}
    workspace = set(meta["workspace_members"])

    # Resolve graph edges: keep every dependency kind except "dev" (None is a
    # normal dependency, "build" is a build-script/proc-macro dependency).
    adjacency: dict[str, list[str]] = {}
    for node in meta["resolve"]["nodes"]:
        adjacency[node["id"]] = []
        for dep in node["deps"]:
            kinds = [k.get("kind") for k in dep.get("dep_kinds", [])]
            if not kinds or any(kind != "dev" for kind in kinds):
                adjacency[node["id"]].append(dep["pkg"])

    roots = [p["id"] for p in meta["packages"] if p["name"] in BINARY_CRATES]

    reachable: set[str] = set()
    stack = list(roots)
    while stack:
        current = stack.pop()
        for nxt in adjacency.get(current, []):
            if nxt not in reachable:
                reachable.add(nxt)
                stack.append(nxt)

    result = []
    for pkg_id in reachable:
        package = packages[pkg_id]
        if pkg_id in workspace:
            continue
        result.append(
            (package["name"], package["version"], license_expression(package))
        )

    result.sort()
    return result


def render(dependencies: list[tuple[str, str, str]]) -> str:
    lines = [
        f"{name} {version} — {license_expr}"
        for name, version, license_expr in dependencies
    ]
    return HEADER + "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if THIRD_PARTY_NOTICES is missing or stale",
    )
    args = parser.parse_args()

    meta = load_metadata()
    try:
        generated = render(third_party_dependencies(meta))
    except MissingLicenseError as exc:
        sys.stderr.write(f"error: {exc}\n")
        return 1

    if args.check:
        current = NOTICES.read_text() if NOTICES.exists() else None
        if current != generated:
            sys.stderr.write(
                "THIRD_PARTY_NOTICES is stale; run "
                "scripts/generate-third-party-notices.py to regenerate it.\n"
            )
            return 1
        return 0

    NOTICES.write_text(generated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
